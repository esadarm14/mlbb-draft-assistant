export function getHeroById(id: string): Hero | undefined {
  return MLBB_HEROES.find(h => h.id.toLowerCase() === id.toLowerCase() || h.name.toLowerCase() === id.toLowerCase());
}

export function searchHeroes(query: string, roleFilter?: string): Hero[] {
  const q = query.trim().toLowerCase();
  return MLBB_HEROES.filter(hero => {
    const matchesQuery = !q || 
      hero.name.toLowerCase().includes(q) || 
      hero.id.toLowerCase().includes(q) ||
      hero.roles.some(r => r.toLowerCase().includes(q)) ||
      hero.lanes.some(l => l.toLowerCase().includes(q));
    
    const matchesRole = !roleFilter || roleFilter === 'All' || hero.roles.includes(roleFilter as any);
    
    return matchesQuery && matchesRole;
  });
}
